await page.locator('#part').selectOption('pi_case_cradle');
const single=await page.evaluate(()=>window.rackViewer.printMeshes.filter(m=>m.visible).map(m=>m.userData.part));
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:root+'/validation/preview-mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
const result={errors,singlePartCorrect:single.length===4&&single.every(v=>v==='pi_case_cradle'),mobileOverflow:overflow};
fs.writeFileSync(root+'/validation/preview-check.json',JSON.stringify(result,null,2));

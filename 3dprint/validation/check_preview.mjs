import {chromium} from '/Users/mk10/.cache/codex/rack-viewer/node_modules/playwright/index.mjs';
import fs from 'node:fs';
const root='/Users/mk10/Desktop/hide_player_flutter/3dprint';
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--use-angle=swiftshader','--enable-webgl','--ignore-gpu-blocklist']});
const page=await browser.newPage({viewport:{width:1480,height:1060},deviceScaleFactor:1});

#!/usr/bin/env python3
"""Generate GB18030 decode tables using Python's standard codec, no runtime dependency."""
from pathlib import Path
out=Path(__file__).resolve().parents[1]/'audio_engine/src/library/Gb18030Tables.inc'
values=[]
for first in range(0x81,0xff):
    for second in list(range(0x40,0x7f))+list(range(0x80,0xff)):
        try: values.append(ord(bytes([first,second]).decode('gb18030')))
        except UnicodeDecodeError: values.append(0xfffd)
ranges=[]
start=previous=last_cp=None
for index in range(126*10*126*10):
    n=index
    fourth=n%10+0x30;n//=10
    third=n%126+0x81;n//=126
    second=n%10+0x30;n//=10
    first=n+0x81
    try: cp=ord(bytes([first,second,third,fourth]).decode('gb18030'))
    except UnicodeDecodeError: cp=None
    if cp is not None and previous is not None and index==previous+1 and cp==last_cp+1:
        previous=index;last_cp=cp
    else:
        if previous is not None:ranges.append((start,previous,last_cp-(previous-start)))
        start=previous=index if cp is not None else None
        last_cp=cp
if previous is not None:ranges.append((start,previous,last_cp-(previous-start)))
with out.open('w') as f:
    f.write('// Generated by scripts/generate_gb18030_tables.py from the Python GB18030 codec.\n')
    f.write('static constexpr uint16_t gbTwoByte[] = {\n')
    for i in range(0,len(values),16):f.write(','.join(hex(n) for n in values[i:i+16])+',\n')
    f.write('};\nstruct GbRange { uint32_t first, last, unicode; };\nstatic constexpr GbRange gbFourByte[] = {\n')
    for row in ranges:f.write('{'+','.join(str(n) for n in row)+'},\n')
    f.write('};\n')
print(len(values),'two-byte entries;',len(ranges),'four-byte ranges')
